def _build_items(class_templates, per_class: int, state_key: str,
                 spec_type: str, prefix: str,
                 rng: random.Random) -> list:
    items = []
    idx = 0
    for label, templates in class_templates:
        per_template, remainder = divmod(per_class, len(templates))
        for t_idx, template in enumerate(templates):
            count = per_template + (1 if t_idx < remainder else 0)
            for _ in range(count):
                text = _fill(template, rng)
                state = {state_key: text}
                if state_key == "ticket":
                    state["channel"] = rng.choice(["email", "chat", "phone"])
                else:
                    state["source"] = rng.choice(
                        ["siem", "edr", "firewall", "user-report"])
                    state["asset"] = rng.choice(HOSTS)
                idx += 1
                items.append({
                    "id": f"{prefix}-{idx:04d}",
                    "state": state,
                    "spec_type": spec_type,
                    "expected": label,
                })
    rng.shuffle(items)
    return items


def build_dataset(kind: str) -> dict:
    """Build one dataset deterministically. ``kind`` in intent/urgency/triage."""
    if kind == "intent":
        rng = random.Random(SEED + 1)
        spec = {"type": "categorical",
                "options": ["billing", "technical", "account",
                            "refund", "shipping"]}
        items = _build_items(INTENT, 100, "ticket", "categorical",
                             "intent", rng)
    elif kind == "urgency":
        rng = random.Random(SEED + 2)
        spec = {"type": "ordinal",
                "levels": ["low", "medium", "high", "critical"]}
        items = _build_items(URGENCY, 125, "event", "ordinal",
                             "urgency", rng)
    elif kind == "triage":
        rng = random.Random(SEED + 3)
        spec = {"type": "categorical",
                "options": ["ignore", "log", "investigate", "escalate"]}
        items = _build_items(TRIAGE, 125, "alert", "categorical",
                             "triage", rng)
    else:
        raise ValueError(f"unknown dataset kind: {kind}")
    return {"name": f"{kind}_500", "version": VERSION, "seed": SEED,
            "spec": spec, "items": items}


def _sha256_file(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def main(out_dir: str = "benchmarks") -> int:
    os.makedirs(out_dir, exist_ok=True)
    checksums = []
    for kind in ("intent", "urgency", "triage"):
        dataset = build_dataset(kind)
        assert len(dataset["items"]) == 500, (kind, len(dataset["items"]))
        path = os.path.join(out_dir, f"{kind}_500.json")
        with open(path, "w", encoding="utf-8") as f:
            json.dump(dataset, f, indent=2, ensure_ascii=False)
            f.write("\n")
        digest = _sha256_file(path)
        checksums.append(f"{digest}  {kind}_500.json")
        print(f"wrote {path} ({len(dataset['items'])} items) sha256={digest[:12]}…")
    cpath = os.path.join(out_dir, "CHECKSUMS.sha256")
    with open(cpath, "w", encoding="utf-8") as f:
        f.write("\n".join(checksums) + "\n")
    print(f"wrote {cpath}")
    return 0


