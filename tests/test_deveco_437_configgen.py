def test_serve_config_overlays_defaults(tmp_path, monkeypatch):
    """serve --config applies the file; explicit flags win."""
    cfg = tmp_path / "hugrgate.yaml"
    cfg.write_text(generate_daemon_config(port=8123, max_batch=4))
    captured = {}

    def fake_daemon(argv):
        captured["argv"] = argv
        return 0

    import hugrgate.daemon
    monkeypatch.setattr(hugrgate.daemon, "main", fake_daemon)
    assert main(["serve", "--config", str(cfg)]) == 0
    argv = captured["argv"]
    assert "--port" in argv
    assert argv[argv.index("--port") + 1] == "8123"
    assert argv[argv.index("--max-batch") + 1] == "4"
    # explicit flag wins over the file
    assert main(["serve", "--config", str(cfg), "--port", "9999"]) == 0
    argv = captured["argv"]
    assert argv[argv.index("--port") + 1] == "9999"


def test_serve_bad_config_is_exit_2(tmp_path):
    bad = tmp_path / "bad.yaml"
    bad.write_text("nope: 1\n")
    assert main(["serve", "--config", str(bad)]) == 2
