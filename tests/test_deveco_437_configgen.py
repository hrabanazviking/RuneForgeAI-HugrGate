def test_init_project_writes_four_files(tmp_path):
    written = init_project(tmp_path)
    names = sorted(p.name for p in written)
    assert names == ["hugrgate.yaml", "policy.yaml", "spec.yaml",
                     "state.example.yaml"]
    # everything it wrote must validate
    from hugrgate.daemon import DaemonConfig
    from hugrgate.serde import policy_from_dict
    from hugrgate.spec import DecisionSpec
    DaemonConfig.from_dict(
        yaml.safe_load((tmp_path / "hugrgate.yaml").read_text()))
    DecisionSpec.from_dict(
        yaml.safe_load((tmp_path / "spec.yaml").read_text()))
    policy_from_dict(
        yaml.safe_load((tmp_path / "policy.yaml").read_text()))


